/**
 * build-knowledge-index.js
 *
 * Builds the retrieval layer for the organization knowledge base.
 *
 *   knowledge/INDEX.md        — the agent-facing catalogue. Every profile loads this
 *                               FIRST so it knows what already exists before it writes
 *                               anything. Without it, agents guess filenames.
 *   data/knowledge-index.json — the same data, machine-readable, for the dashboard.
 *
 * For each Markdown file it records: path, title (first `# ` heading), summary (first
 * prose line), owning profile (from `07-agent-outputs` filenames or frontmatter),
 * size, and last-modified date.
 *
 * Regenerated by server.js at boot and after every knowledge write, or standalone:
 *   npm run build:index
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const SKIP_FILES = new Set(["INDEX.md"]);

const FOLDER_LABELS = {
  "00-org": "Organization constitution — read before anything else",
  "01-brand": "Brand Kit, personas, voice & tone, messaging",
  "02-market-research": "Competitors, market sizing, VoC, account dossiers",
  "03-campaigns": "Plans, calendars, launches, work orders",
  "04-content": "Drafts, SEO briefs, copy, email, social, video, assets",
  "05-analytics-reports": "Performance reports, experiments, budget, compliance",
  "06-playbooks": "Reusable how-we-do-things documents",
  "07-agent-outputs": "Raw dated agent outputs awaiting curation",
};

const PROTECTED = new Set(require("./protected-dirs.js").PROTECTED_DIRS);

function parse(file, rel) {
  const src = fs.readFileSync(file, "utf8");
  const body = src.replace(/^---\n[\s\S]*?\n---\n?/, "");
  const fm = src.match(/^---\n([\s\S]*?)\n---/);
  const fmGet = (k) => {
    const m = fm && fm[1].match(new RegExp(`^${k}:\\s*(.*)$`, "m"));
    return m ? m[1].trim().replace(/^["']|["']$/g, "") : "";
  };

  const titleMatch = body.match(/^#\s+(.+)$/m);
  const title = fmGet("title") || (titleMatch ? titleMatch[1].trim() : path.basename(rel, path.extname(rel)));

  // First prose line: skip headings, blockquotes, lists, tables, images, rules.
  let summary = fmGet("summary") || fmGet("description") || "";
  if (!summary) {
    for (const line of body.split("\n")) {
      const t = line.trim();
      if (!t || /^[#>|!\-*=_]/.test(t) || /^\d+\./.test(t)) continue;
      summary = t;
      break;
    }
  }
  summary = summary.replace(/[*`_]/g, "").slice(0, 160);

  // Owner: frontmatter wins, then the 07-agent-outputs filename convention.
  let owner = fmGet("profile") || fmGet("owner");
  if (!owner) {
    const m = path.basename(rel).match(/^\d{4}-\d{2}-\d{2}--([a-z0-9-]+)--/);
    if (m) owner = m[1];
  }

  const st = fs.statSync(file);
  return {
    path: rel,
    folder: rel.includes("/") ? rel.split("/")[0] : "(root)",
    title, summary, owner: owner || null,
    size: st.size,
    updated: st.mtime.toISOString().slice(0, 10),
    readOnlyInChat: PROTECTED.has(rel.split("/")[0]),
  };
}

function walk(dir, rel, out) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (e.name.startsWith(".")) continue;
    const childRel = rel ? `${rel}/${e.name}` : e.name;
    const abs = path.join(dir, e.name);
    if (e.isDirectory()) walk(abs, childRel, out);
    // `_`-prefixed files are templates (e.g. work-order _TEMPLATE.md). Indexing them
    // makes their placeholder frontmatter look like a real document with a real owner.
    else if (e.name.startsWith("_")) continue;
    else if (/\.(md|markdown|txt)$/i.test(e.name) && !SKIP_FILES.has(childRel)) {
      try { out.push(parse(abs, childRel)); } catch { /* unreadable file — skip */ }
    }
  }
  return out;
}

function renderMarkdown(entries) {
  const byFolder = new Map();
  for (const e of entries) {
    if (!byFolder.has(e.folder)) byFolder.set(e.folder, []);
    byFolder.get(e.folder).push(e);
  }
  const folders = [...byFolder.keys()].sort();

  const lines = [
    "# 📇 Knowledge Index",
    "",
    "> **Generated file — do not edit.** Rebuilt by the Admin server on every knowledge",
    "> change. Editing it by hand will be overwritten.",
    "",
    `Catalogue of the organization knowledge base — **${entries.length} document${entries.length === 1 ? "" : "s"}** across ${folders.length} folder${folders.length === 1 ? "" : "s"}.`,
    "",
    "## How to use this",
    "",
    "1. **Read this file first.** It is the cheapest way to learn what the organization",
    "   already knows.",
    "2. **Then open only what you need** — the two or three documents relevant to your task,",
    "   plus the context list in your own profile.",
    "3. **If nothing here covers your topic**, that gap is itself a finding: say so, and",
    "   create the missing document rather than duplicating an existing one under a new name.",
    "4. **Never guess a path.** If it is not in this index, it does not exist.",
    "",
    "🔒 = read-only in chat (curated organization brain — draft to `07-agent-outputs/` and",
    "hand off to the Marketing Director to change it).",
    "",
  ];

  // A folder outside the standard eight is invisible to governance: no owner
  // convention, no read-only mount, no promotion path. A lookalike (01-brand-v2/)
  // could otherwise masquerade as doctrine — flag it wherever agents read.
  const unknown = folders.filter((f) => f !== "(root)" && !FOLDER_LABELS[f]);
  if (unknown.length) {
    lines.push(
      "> ⚠️ **Non-standard folders present:** " + unknown.map((f) => `\`${f}/\``).join(", ") + ".",
      "> These are NOT part of the governed structure — nothing in them is curated",
      "> doctrine, and the read-only-brain guarantee does not cover them. Do not treat",
      "> their contents as approved organization knowledge.",
      "");
  }

  for (const folder of folders) {
    const items = byFolder.get(folder).sort((a, b) => a.path.localeCompare(b.path));
    const label = FOLDER_LABELS[folder];
    const lock = PROTECTED.has(folder) ? " 🔒" : "";
    lines.push(`## \`${folder}/\`${lock}`, "");
    if (label) lines.push(`_${label}_`, "");
    else if (folder !== "(root)") lines.push("_⚠️ Non-standard folder — not governed, not curated doctrine._", "");
    lines.push("| Document | What's in it | Owner | Updated |", "| --- | --- | --- | --- |");
    for (const it of items) {
      const summary = (it.summary || "—").replace(/\|/g, "\\|");
      lines.push(`| \`${it.path}\` — **${it.title.replace(/\|/g, "\\|")}** | ${summary} | ${it.owner || "—"} | ${it.updated} |`);
    }
    lines.push("");
  }

  const empty = Object.keys(FOLDER_LABELS).filter((f) => !byFolder.has(f));
  if (empty.length) {
    lines.push("## Empty folders", "",
      "Nothing has been written here yet — these are open gaps in the organization's knowledge:", "",
      ...empty.map((f) => `- \`${f}/\` — ${FOLDER_LABELS[f]}`), "");
  }

  lines.push("---", "", `_Last built: ${new Date().toISOString().replace("T", " ").slice(0, 16)} UTC_`, "");
  return lines.join("\n");
}

/**
 * @param {string} knowledgeDir absolute path to the knowledge base
 * @param {string} [jsonOut] absolute path for the machine-readable index
 * @returns {{documents: number, folders: number, entries: object[]}}
 */
function buildKnowledgeIndex(knowledgeDir, jsonOut) {
  const entries = walk(knowledgeDir, "", []);
  fs.writeFileSync(path.join(knowledgeDir, "INDEX.md"), renderMarkdown(entries), "utf8");
  const payload = { builtAt: new Date().toISOString(), documents: entries.length, entries };
  if (jsonOut) {
    fs.mkdirSync(path.dirname(jsonOut), { recursive: true });
    fs.writeFileSync(jsonOut, JSON.stringify(payload, null, 2), "utf8");
  }
  return { documents: entries.length, folders: new Set(entries.map((e) => e.folder)).size, entries };
}

module.exports = { buildKnowledgeIndex };

if (require.main === module) {
  const r = buildKnowledgeIndex(path.join(ROOT, "knowledge"), path.join(ROOT, "data", "knowledge-index.json"));
  console.log(`Indexed ${r.documents} documents across ${r.folders} folders → knowledge/INDEX.md`);
}
